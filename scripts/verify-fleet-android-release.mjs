import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
const meta=JSON.parse(fs.readFileSync('public/downloads/fleet-android.json','utf8'));
const apk='public'+meta.url;
const bytes=fs.readFileSync(apk);
assert.equal(bytes.length,meta.bytes,'Published APK size');
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),meta.sha256,'Published APK checksum');
for(const alias of ['DropX-Fleet.apk','DropX-Fleet-32bit.apk'])assert.deepEqual(fs.readFileSync('public/downloads/'+alias),bytes,'Current APK aliases must be universal and identical');
const sdk=process.env.ANDROID_HOME;
assert.ok(sdk,'Set ANDROID_HOME to run APK release verification');
const tool=fs.readdirSync(sdk+'/build-tools').filter(v=>!v.includes('-')).sort((a,b)=>a.localeCompare(b,undefined,{numeric:true})).at(-1);
const signature=execFileSync(`${sdk}/build-tools/${tool}/apksigner`,['verify','--verbose','--print-certs',apk],{encoding:'utf8'});
assert.match(signature,/Verified using v2 scheme \(APK Signature Scheme v2\): true/);
const fingerprint=signature.match(/Signer #1 certificate SHA-256 digest: (\w+)/)?.[1];
assert.equal(fingerprint,'f9785e7ad5f958cbc32b82f6bd9947472e1e8ea358542ce4dc61a94913370986','Preserve the installed Fleet signing identity');
const assetlinks=fs.readFileSync('src/app/.well-known/assetlinks.json/route.ts','utf8');
assert.ok(assetlinks.includes(fingerprint.match(/../g).join(':').toUpperCase()),'Digital Asset Links signing certificate');
const badging=execFileSync(`${sdk}/build-tools/${tool}/aapt`,['dump','badging',apk],{encoding:'utf8'});
assert.ok(badging.includes(`name='${meta.packageName}' versionCode='${meta.versionCode}' versionName='${meta.version}'`));
assert.ok(!badging.includes('application-debuggable'),'Never publish debuggable APK');
assert.ok(!badging.includes('native-code:'),'One APK supports all CPU architectures');
assert.match(badging,/application-icon-\d+:/,'Branded launcher icon packaged');
console.log('Fleet Android release: checksum, aliases, version, signature, asset links, release mode, icons and universal architecture passed.');
