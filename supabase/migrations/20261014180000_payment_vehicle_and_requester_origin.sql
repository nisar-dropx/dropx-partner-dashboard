comment on column public.payment_requests.adhoc_approval_steps is 'Server-verified request approval snapshot. Also used for manager-raised requests to preserve the independent approval chain.';

alter table public.payment_heads add column if not exists vehicle_scope_updated_by uuid references public.profiles(id);
create table public.payment_head_vehicle_policy_changes (
  id uuid primary key default gen_random_uuid(), company_id uuid not null,
  payment_head_id uuid not null references public.payment_heads(id),
  previous_scope text, new_scope text not null, actor_id uuid references public.profiles(id),
  changed_at timestamptz not null default now()
);
alter table public.payment_head_vehicle_policy_changes enable row level security;
revoke all on public.payment_head_vehicle_policy_changes from anon, authenticated;
grant all on public.payment_head_vehicle_policy_changes to service_role;
create index payment_head_vehicle_policy_history on public.payment_head_vehicle_policy_changes(company_id,payment_head_id,changed_at desc);
create or replace function public.log_payment_head_vehicle_policy() returns trigger
language plpgsql set search_path=public as $$
begin
  if tg_op='UPDATE' and new.vehicle_scope is not distinct from old.vehicle_scope then return new; end if;
  if auth.role() in ('authenticated','anon') then raise exception 'Use the authorized Payment Heads action.'; end if;
  if new.vehicle_scope_updated_by is not null and not exists(select 1 from public.profiles where id=new.vehicle_scope_updated_by and company_id=new.company_id and is_active) then
    raise exception 'Invalid vehicle policy actor';
  end if;
  insert into public.payment_head_vehicle_policy_changes(company_id,payment_head_id,previous_scope,new_scope,actor_id)
  values(new.company_id,new.id,case when tg_op='UPDATE' then old.vehicle_scope else null end,new.vehicle_scope,new.vehicle_scope_updated_by);
  return new;
end $$;
create trigger payment_head_vehicle_policy_audit after insert or update of vehicle_scope on public.payment_heads
  for each row execute function public.log_payment_head_vehicle_policy();

