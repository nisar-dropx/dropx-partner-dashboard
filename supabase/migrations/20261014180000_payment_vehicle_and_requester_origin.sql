-- These fields are generated by authenticated server actions, not accepted
-- from client-side table writes. Existing requests remain backward-compatible.
create or replace function public.guard_payment_request_provenance() returns trigger
language plpgsql set search_path=public as $$
begin
  if auth.role() in ('authenticated','anon') and (
    (tg_op='INSERT' and (new.approval_origin is not null or new.expense_vehicle_id is not null or new.expense_vehicle_snapshot is not null or new.adhoc_approval_steps is not null)) or
    (tg_op='UPDATE' and (new.approval_origin,new.expense_vehicle_id,new.expense_vehicle_snapshot,new.adhoc_approval_steps)
      is distinct from (old.approval_origin,old.expense_vehicle_id,old.expense_vehicle_snapshot,old.adhoc_approval_steps))
  ) then raise exception 'Use the authorized payment request action to update routing or vehicle details.'; end if;
  if new.expense_vehicle_id is not null and (tg_op='INSERT' or new.expense_vehicle_id is distinct from old.expense_vehicle_id or new.location_id is distinct from old.location_id) then
    if not exists (
      select 1 from public.fleet_vehicles v
      join public.stations s on s.company_id=new.company_id and s.id=new.location_id and s.station_code=v.station_code
      left join public.fleet_vehicle_sources vs on vs.id=v.source_id and vs.company_id=v.company_id
      where v.company_id=new.company_id and v.id=new.expense_vehicle_id
        and (case when v.source_id is null then v.ownership_type else vs.ownership_type end)='own'
        and v.status not in ('sold','disposed','returned','inactive')
    ) then raise exception 'Expense vehicle must be company-owned and assigned to the request station.'; end if;
  end if;
  return new;
end $$;
create trigger payment_request_provenance_guard before insert or update on public.payment_requests
  for each row execute function public.guard_payment_request_provenance();
